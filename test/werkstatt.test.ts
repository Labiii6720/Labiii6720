/** Attrappe des Slicers: schreibt die G-Code-Datei hinter --output wie PrusaSlicer. */
function schreibtGcode(inhalt = PRUSA_GCODE): (cmd: string) => Ergebnis {
  return (cmd) => {
    const m = /--output '((?:[^']|'\\'')*)'/.exec(cmd);
    assert.ok(m, `kein --output in ${cmd}`);
    writeFileSync(m[1]!.replace(/'\\''/g, "'"), inhalt);
    return { stdout: "Slicing result exported to …" };
  };
}

