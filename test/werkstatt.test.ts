// ---------- Prozessgruppe (echte exec-Funktion, Prozessstart, Signale und Zeitgeber als Attrappen) ----------

describe("Zeitlimit beendet die ganze Prozessgruppe", () => {
  interface Kind extends EventEmitter { pid: number; stdout: PassThrough; stderr: PassThrough }
  interface Timer { ms: number; fn: () => void; aktiv: boolean }
  let kinder: { befehl: string; argumente: string[]; opts: SpawnOptions; kind: Kind }[];
  let signale: [number, string][];
  let timer: Timer[];
  const tick = () => new Promise<void>((r) => setImmediate(r));
  const feuere = (ms: number) => {
    const t = timer.find((x) => x.aktiv && x.ms === ms);
    assert.ok(t, `kein aktiver Zeitgeber über ${ms} ms`);
    t.aktiv = false;
    t.fn();
  };

  beforeEach(() => {
    kinder = [];
    signale = [];
    timer = [];
    abhaengigkeiten.exec = echt.exec;
    abhaengigkeiten.spawn = (befehl, argumente, opts) => {
      const kind = Object.assign(new EventEmitter(), { pid: 4242 + kinder.length, stdout: new PassThrough(), stderr: new PassThrough() });
      kinder.push({ befehl, argumente, opts, kind });
      return kind as unknown as ChildProcess;
    };
    abhaengigkeiten.signal = (pid, sig) => { signale.push([pid, sig]); };
    abhaengigkeiten.nachZeit = (ms, fn) => {
      const t = { ms, fn, aktiv: true };
      timer.push(t);
      return () => { t.aktiv = false; };
    };
  });

  it("slice: SIGTERM an die Gruppe, nach der Gnadenfrist SIGKILL; frei erst nach Prozessende", async () => {
    const quelle = stl("cad/teil.stl");
    let erledigt = false;
    const lauf = slice("cad/teil.stl").finally(() => { erledigt = true; });
    lauf.catch(() => {});
    assert.equal(kinder.length, 1);
    const { befehl, argumente, opts, kind } = kinder[0]!;
    assert.equal(befehl, "/bin/sh");
    assert.deepEqual(argumente, ["-c", `${q(slicerBin)} --export-gcode --load ${q(profil)} --output ${q(ws("cad/teil.gcode"))} ${q(quelle)}`]);
    assert.equal(opts.detached, true, "eigene Prozessgruppe");
    assert.equal(opts.cwd, ROOT);
    assert.equal(opts.env?.OCTOPRINT_KEY, undefined);

    feuere(600_000);
    assert.deepEqual(signale, [[-4242, "SIGTERM"]], "Signal an die Gruppe (negative PID), nicht nur an die Shell");
    await tick();
    assert.equal(erledigt, false, "solange der Slicer lebt, ist der Lauf nicht vorbei");
    await assert.rejects(slice("cad/teil.stl"), /läuft bereits/);

    feuere(GNADENFRIST_MS);
    assert.deepEqual(signale.at(-1), [-4242, "SIGKILL"]);
    // Der verwaiste Slicer schreibt noch etwas, dann ist die Gruppe tot
    writeFileSync(ws("cad/teil.gcode"), "; halb");
    kind.stderr.write("Generating perimeters\n");
    await tick();
    kind.emit("close", null, "SIGKILL");
    await assert.rejects(lauf, /Slicen abgebrochen: PrusaSlicer war nach 10 min 0 s nicht fertig[\s\S]*Generating perimeters/);
    assert.equal(existsSync(ws("cad/teil.gcode")), false, "halbe Datei entfernt, nachdem der Prozess wirklich weg ist");
    assert.equal(timer.filter((t) => t.aktiv).length, 0, "keine Zeitgeber übrig");

    // Danach wieder frei
    const zweiter = slice("cad/teil.stl");
    const k2 = kinder[1]!.kind;
    writeFileSync(ws("cad/teil.gcode"), "; neu\n");
    k2.stdout.write("Slicing result exported\n");
    await tick();
    k2.emit("close", 0, null);
    assert.equal((await zweiter).gcodePath, ws("cad/teil.gcode"));
  });

  it("Gruppe endet auf SIGTERM: Nachzügler bekommen SIGKILL, Gnadenfrist wird gestoppt", async () => {
    const fertig = new Promise<{ err: ExecException | null; stdout: string }>((r) => {
      abhaengigkeiten.exec("x", { cwd: temp, timeout: 50 }, (err, stdout) => r({ err, stdout }));
    });
    feuere(50);
    kinder[0]!.kind.emit("close", null, "SIGTERM");
    const { err } = await fertig;
    assert.equal(err?.killed, true);
    assert.equal(err?.signal, "SIGTERM");
    assert.equal(err?.code, null);
    assert.deepEqual(signale, [[-4242, "SIGTERM"], [-4242, "SIGKILL"]]);
    assert.equal(timer.filter((t) => t.aktiv).length, 0);
  });

  it("normales Ende: Ausgabe, Exit-Code, keine Signale", async () => {
    const ok = new Promise<{ err: ExecException | null; stdout: string; stderr: string }>((r) => {
      abhaengigkeiten.exec("x", { cwd: temp, timeout: 1_000 }, (err, stdout, stderr) => r({ err, stdout, stderr }));
    });
    kinder[0]!.kind.stdout.write("hallo ");
    kinder[0]!.kind.stdout.write("welt");
    kinder[0]!.kind.stderr.write("warnung");
    await tick();
    kinder[0]!.kind.emit("close", 0, null);
    assert.deepEqual(await ok, { err: null, stdout: "hallo welt", stderr: "warnung" });

    const fehl = new Promise<ExecException | null>((r) => { abhaengigkeiten.exec("y", { cwd: temp }, (err) => r(err)); });
    kinder[1]!.kind.emit("close", 2, null);
    const err = await fehl;
    assert.equal(err?.code, 2);
    assert.equal(err?.killed, false);
    assert.deepEqual(signale, []);
    assert.equal(timer.filter((t) => t.aktiv).length, 0);
  });

  it("Pufferüberlauf beendet die Gruppe und gilt nicht als Zeitlimit", async () => {
    const fertig = new Promise<{ err: ExecException | null; stdout: string }>((r) => {
      abhaengigkeiten.exec("x", { cwd: temp, maxBuffer: 5 }, (err, stdout) => r({ err, stdout }));
    });
    kinder[0]!.kind.stdout.write("0123456789");
    await tick();
    assert.deepEqual(signale, [[-4242, "SIGTERM"]]);
    kinder[0]!.kind.emit("close", null, "SIGTERM");
    const { err, stdout } = await fertig;
    assert.equal(err?.code, "ERR_CHILD_PROCESS_STDIO_MAXBUFFER");
    assert.equal(stdout, "01234");
  });

  it("Startfehler → genau ein Rückruf mit Fehler", async () => {
    let rueckrufe = 0;
    const fertig = new Promise<ExecException | null>((r) => {
      abhaengigkeiten.exec("x", { cwd: temp, timeout: 1_000 }, (err) => { rueckrufe++; r(err); });
    });
    const k = kinder[0]!.kind;
    k.emit("error", Object.assign(new Error("spawn /bin/sh ENOENT"), { code: "ENOENT" }));
    k.emit("close", -2, null);
    assert.match(String((await fertig)?.message), /ENOENT/);
    assert.equal(rueckrufe, 1);
    assert.equal(timer.filter((t) => t.aktiv).length, 0);
  });

  describe("Signal an Jarvis beendet laufende Gruppen mit (Strg-C, systemctl, Elternprozess)", () => {
    const zahl = () => ({ SIGINT: process.listenerCount("SIGINT"), SIGTERM: process.listenerCount("SIGTERM"), SIGHUP: process.listenerCount("SIGHUP"), exit: process.listenerCount("exit") });
    let ausgeloest: string[];
    let fremde: Map<string, ((...a: unknown[]) => void)[]>;
    beforeEach(() => {
      ausgeloest = [];
      abhaengigkeiten.erneutAusloesen = (sig) => { ausgeloest.push(sig); };
      // Fremde Handler (Testläufer) kurz weg, damit «niemand sonst hört zu» prüfbar ist
      fremde = new Map();
      for (const sig of ["SIGINT", "SIGTERM", "SIGHUP"] as const) {
        fremde.set(sig, process.listeners(sig) as ((...a: unknown[]) => void)[]);
        process.removeAllListeners(sig);
      }
    });
    afterEach(() => {
      for (const [sig, liste] of fremde) for (const f of liste) process.on(sig as NodeJS.Signals, f);
    });
    const starte = () => new Promise<ExecException | null>((r) => { abhaengigkeiten.exec("x", { cwd: temp, timeout: 1_000 }, (err) => r(err)); });

    it("SIGTERM: SIGKILL an jede laufende Gruppe, Handler weg, Signal erneut ausgelöst", async () => {
      const basis = zahl();
      const a = starte();
      const b = starte();
      assert.deepEqual(zahl(), { SIGINT: basis.SIGINT + 1, SIGTERM: basis.SIGTERM + 1, SIGHUP: basis.SIGHUP + 1, exit: basis.exit + 1 }, "einmal registriert, nicht je Lauf");
      process.emit("SIGTERM", "SIGTERM");
      assert.deepEqual(signale, [[-4242, "SIGKILL"], [-4243, "SIGKILL"]]);
      assert.deepEqual(ausgeloest, ["SIGTERM"]);
      assert.deepEqual(zahl(), basis);
      kinder[0]!.kind.emit("close", null, "SIGKILL");
      kinder[1]!.kind.emit("close", null, "SIGKILL");
      assert.equal((await a)?.signal, "SIGKILL");
      assert.equal((await b)?.signal, "SIGKILL");
      assert.deepEqual(zahl(), basis);
    });

    it("SIGINT mit eigenem Handler (server.ts, setup.ts): Gruppe beendet, nicht erneut ausgelöst", async () => {
      const eigener = () => {};
      process.on("SIGINT", eigener);
      try {
        const a = starte();
        process.emit("SIGINT", "SIGINT");
        assert.deepEqual(signale, [[-4242, "SIGKILL"]]);
        assert.deepEqual(ausgeloest, [], "der andere Handler entscheidet über das Ende");
        kinder[0]!.kind.emit("close", null, "SIGKILL");
        await a;
      } finally {
        process.removeListener("SIGINT", eigener);
      }
    });

    it("Prozessende (exit) tötet die Gruppe synchron; nach normalem Ende keine Handler und kein Signal", async () => {
      const basis = zahl();
      const vorher = process.listeners("exit");
      const a = starte();
      const neu = process.listeners("exit").filter((f) => !vorher.includes(f));
      assert.equal(neu.length, 1);
      (neu[0] as () => void)();
      assert.deepEqual(signale, [[-4242, "SIGKILL"]]);
      kinder[0]!.kind.emit("close", null, "SIGKILL");
      await a;
      assert.deepEqual(zahl(), basis);

      signale.length = 0;
      const b = starte();
      kinder[1]!.kind.emit("close", 0, null);
      assert.equal(await b, null);
      assert.deepEqual(zahl(), basis, "Handler nach dem letzten Lauf entfernt");
      process.emit("SIGHUP", "SIGHUP");
      assert.deepEqual(signale, []);
      assert.deepEqual(ausgeloest, []);
    });
  });

  it("Selbsttest: --help hängt → Gruppe beendet, Meldung «reagiert nicht»", async () => {
    const lauf = selbsttest(["Slicer"]);
    while (!kinder.length) await tick();
    assert.equal(kinder[0]!.argumente[1], `${q(slicerBin)} --help`);
    feuere(10_000);
    kinder[0]!.kind.emit("close", null, "SIGTERM");
    const [b] = await lauf;
    assert.equal(b!.status, "fehler");
    assert.match(b!.info, /reagiert nicht/);
    assert.deepEqual(signale[0], [-4242, "SIGTERM"]);
  });
});
