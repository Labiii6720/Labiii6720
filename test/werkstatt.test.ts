  "; generated by PrusaSlicer 2.7.1+linux-x64-GTK3 on 2026-10-11 at 10:00:00 UTC",
  "M107",
  ";LAYER_CHANGE",
  ";Z:0.2",
  "G1 Z.2 F720",
  ";LAYER_CHANGE",
  ";Z:0.4",
  ";LAYER_CHANGE",
