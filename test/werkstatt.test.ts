interface Upload { url: string; method: string; key: string | null; datei?: string; inhalt?: string; print?: string; select?: string }
const uploads: Upload[] = [];
let antworten: (Response | Error)[] = [];
const echteFetch = globalThis.fetch;
globalThis.fetch = (async (eingabe: string | URL | Request, init?: RequestInit) => {
  const form = init?.body instanceof FormData ? init.body : undefined;
  const datei = form?.get("file");
  uploads.push({
    url: String(eingabe),
    method: init?.method ?? "GET",
    key: new Headers(init?.headers).get("X-Api-Key"),
    datei: datei instanceof File ? datei.name : undefined,
    inhalt: datei instanceof File ? await datei.text() : undefined,
    print: form?.get("print")?.toString(),
    select: form?.get("select")?.toString(),
  });
  const a = antworten.shift();
  if (!a) throw new Error("Attrappe: keine Antwort mehr vorgesehen");
  if (a instanceof Error) throw a;
  return a;
}) as typeof fetch;
after(() => { globalThis.fetch = echteFetch; });

